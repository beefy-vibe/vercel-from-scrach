-- This script shows the configuration needed for OAuth providers
-- You'll need to configure these in your Supabase Dashboard under Authentication > Providers

-- Google OAuth Configuration:
-- 1. Go to Google Cloud Console
-- 2. Create OAuth 2.0 credentials
-- 3. Add your Supabase callback URL: https://your-project.supabase.co/auth/v1/callback
-- 4. Add the Client ID and Client Secret to Supabase Dashboard

-- Apple OAuth Configuration:
-- 1. Go to Apple Developer Console
-- 2. Create a Services ID for Sign in with Apple
-- 3. Configure the domain and redirect URL in Apple Developer Console
-- 4. Generate a private key and create the client secret
-- 5. Add the configuration to Supabase Dashboard

-- Note: The actual OAuth provider setup is done through the Supabase Dashboard UI
